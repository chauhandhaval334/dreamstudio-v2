require("dotenv").config();

const postgres = require("../src/config/postgres");

async function createSchema() {
  try {
    console.log("🚀 Creating schema...");
await postgres.query(`
    DROP TABLE IF EXISTS dream_images CASCADE;
    DROP TABLE IF EXISTS dream_images_digs CASCADE;
    DROP TABLE IF EXISTS tbl_subscription CASCADE;
`);

    await postgres.query(`
      CREATE TABLE IF NOT EXISTS dream_images (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          path TEXT NOT NULL,
          "thumbPath" VARCHAR(500),
          prompt TEXT NOT NULL,
          time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          "modelName" VARCHAR(30),
          "stylePreset" VARCHAR(30),
          "aspectRatio" VARCHAR(10),
          country VARCHAR(200),
          approved INTEGER DEFAULT 0,
          feedback VARCHAR(1000) DEFAULT 'no feedback',
          version_code VARCHAR(20),
          "deviceId" VARCHAR(100),
          "isPremium" BIGINT DEFAULT 0,
          extraa VARCHAR(500) DEFAULT '',
          "likeCount" INTEGER DEFAULT 0
      );
    `);

    console.log("✅ dream_images");

    await postgres.query(`
      CREATE TABLE IF NOT EXISTS dream_images_digs (
          id INTEGER PRIMARY KEY,
          path TEXT NOT NULL,
          prompt TEXT NOT NULL,
          time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
          "modelName" VARCHAR(30),
          "stylePreset" VARCHAR(15),
          "aspectRatio" VARCHAR(10),
          country VARCHAR(30),
          approved INTEGER DEFAULT 0
      );
    `);

    console.log("✅ dream_images_digs");

    await postgres.query(`
      CREATE TABLE IF NOT EXISTS tbl_subscription (
          order_id VARCHAR(100) PRIMARY KEY,
          device_id VARCHAR(100),
          package_name VARCHAR(50),
          sku VARCHAR(20),
          time BIGINT,
          available_token INTEGER,
          total_token INTEGER,
          "isBlocked" INTEGER DEFAULT 0,
          last_used BIGINT DEFAULT 0,
          version_code VARCHAR(50),
          "deviceId" VARCHAR(100)
      );
    `);

    console.log("✅ tbl_subscription");

    console.log("");
    console.log("🎉 Schema Created Successfully");

    process.exit(0);

  } catch (err) {
    console.error(err);
    process.exit(1);
  }
}

createSchema();
